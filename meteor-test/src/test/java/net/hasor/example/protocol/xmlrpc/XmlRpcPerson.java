package net.hasor.example.protocol.xmlrpc;

/** 业务对象由 XML-RPC struct 承载，数组保留接口中的泛型元素类型。 */
public class XmlRpcPerson {
    private String name;
    private int    age;

    public String getName() {
        return this.name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return this.age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
